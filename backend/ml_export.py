def _json_literal(value):
    return json.dumps(value, ensure_ascii=True, indent=4)


def _build_models_config(models: list[ClassifierConfig]) -> str:
    normalized = [{"id": model.id, "params": normalize_model_params(model.id, model.params)} for model in models]
    return _json_literal(normalized)


def generate_fusion_calculator_export_code(fusion_method: str, sources: list) -> tuple[str, str]:
    normalized_sources = [
        {
            "name": source.name,
            "masses": {str(key): float(value) for key, value in source.masses.items()},
        }
        for source in sources
    ]

    script = "\n\n".join(
        [
            "# Generated by FusionLab. Minimal runnable export.",
            "\n".join(
                [
                    "from pybelief.core.belief_mass import BeliefMass",
                    "from pybelief.fusion.dempster import combine_multiple as dempster_fusion",
                    "from pybelief.fusion.pcr import combine_multiple as pcr5_fusion, combine_multiple_pcr6 as pcr6_fusion",
                ]
            ),
            "\n".join(
                [
                    f"FUSION_METHOD = {fusion_method!r}",
                    f"SOURCES = {_json_literal(normalized_sources)}",
                ]
            ),
            dedent(
                """
                def build_belief_mass(source):
                    masses = {
                        frozenset([hypothesis]): mass
                        for hypothesis, mass in source["masses"].items()
                    }
                    return BeliefMass(masses)


                def main():
                    belief_masses = [build_belief_mass(source) for source in SOURCES]

                    if FUSION_METHOD == "dempster":
                        fused, conflict = dempster_fusion(belief_masses)
                    elif FUSION_METHOD == "pcr5":
                        fused, conflict = pcr5_fusion(belief_masses)
                    elif FUSION_METHOD == "pcr6":
                        fused, conflict = pcr6_fusion(belief_masses)
                    else:
                        raise ValueError(f"Unknown fusion method: {FUSION_METHOD}")

                    result = {",".join(sorted(hypothesis)): mass for hypothesis, mass in fused.items()}
                    print("Done.")
                    print("Fusion method:", FUSION_METHOD)
                    print("Result masses:", result)
                    print("Conflict:", conflict)


                if __name__ == "__main__":
                    main()
                """
            ).strip(),
        ]
    ).strip() + "\n"

    return script, f"fusion_export_{fusion_method}.py"


